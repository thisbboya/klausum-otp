#!/usr/bin/env node
// Regenerates src/disposable-domains.ts from the community list (CC0, public domain):
// https://github.com/disposable-email-domains/disposable-email-domains
//   npm run update:disposable
// Run monthly (see docs/MAINTENANCE.md); CI tests catch a broken download.
import { writeFileSync } from "node:fs";

const URL = "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf";
// Extra domains we've seen abused that the list doesn't have yet (lower-case, one per entry).
const EXTRA = [];

const res = await fetch(URL);
if (!res.ok) throw new Error(`download failed: ${res.status}`);
const domains = [...new Set(
  (await res.text()).split(/\r?\n/).map((l) => l.trim().toLowerCase()).filter((l) => l && !l.startsWith("#")).concat(EXTRA),
)].sort();
if (domains.length < 5000) throw new Error(`list looks wrong: only ${domains.length} domains`);

writeFileSync("src/disposable-domains.ts",
  `// GENERATED by scripts/update-disposable.mjs on ${new Date().toISOString().slice(0, 10)} — do not edit.\n` +
  `// Source: disposable-email-domains/disposable-email-domains (CC0 1.0). ${domains.length} domains.\n` +
  `export const DISPOSABLE_DOMAINS: ReadonlySet<string> = new Set(${JSON.stringify(domains.join("\n"))}.split("\\n"));\n`);
console.log(`wrote ${domains.length} domains`);
